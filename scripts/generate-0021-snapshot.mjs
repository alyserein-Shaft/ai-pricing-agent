#!/usr/bin/env node
/**
 * Generate drizzle-active/meta/0022_snapshot.json from the LIVE post-0021 schema.
 *
 * WHY THIS EXISTS
 * 0021 was authored as hand-written additive SQL plus a hand-added journal entry,
 * which left `scripts/check-active-chain-consistency.mjs` reporting two real
 * inconsistencies: snapshot count != journal entry count, and the newest snapshot
 * not matching the newest journal tag. The snapshot must exist or the chain
 * contract is broken for the next `drizzle-kit generate`.
 *
 * It is DERIVED FROM THE LIVE DATABASE, not hand-written, because the live
 * database is the authoritative record of what 0021 actually produced. The
 * predecessor snapshot's entries are copied verbatim so no existing table is
 * silently rewritten.
 *
 * Precedent for omitting an index: 0020's snapshot carries
 * `drawing_quantity_claims_project_head_idx` and `..._class_idx` but NOT
 * `..._current_identity_idx`, because that index is a UNIQUE index over
 * COALESCE(...) expressions which the drizzle snapshot shape cannot represent.
 * The same rule is applied to `drawing_quantity_expected_scope_current_identity_idx`
 * so the two snapshots are generated by the same convention. The index still
 * EXISTS in the database -- it is simply not snapshot-representable.
 *
 * Usage: node scripts/generate-0021-snapshot.mjs <db>
 */
import { DatabaseSync } from "node:sqlite";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const META = join(ROOT, "drizzle-active", "meta");
const dbPath = process.argv[2];
if (!dbPath) throw new Error("Usage: <db>");

const prev = JSON.parse(readFileSync(join(META, "0022_snapshot.json"), "utf8"));
const target = join(META, "0022_snapshot.json");
if (existsSync(target)) throw new Error(`refusing to overwrite existing ${target}`);

const db = new DatabaseSync(dbPath, { readOnly: true });
const all = (s, ...a) => db.prepare(s).all(...a);

/** Unrepresentable (COALESCE/partial-unique) indexes are omitted, as in 0020. */
const isSnapshotRepresentable = (sql) => !/COALESCE/i.test(sql);

const sqliteTypeToDrizzle = (t) => {
  const s = String(t || "text").toLowerCase();
  if (s.includes("int")) return "integer";
  if (s.includes("real") || s.includes("floa") || s.includes("doub")) return "real";
  if (s.includes("blob")) return "blob";
  return "text";
};

function buildTable(name) {
  const columns = {};
  for (const c of all(`PRAGMA table_info(${name})`)) {
    const col = {
      name: c.name,
      type: sqliteTypeToDrizzle(c.type),
      primaryKey: c.pk === 1,
      notNull: c.notnull === 1,
      autoincrement: false,
    };
    if (c.dflt_value !== null) col.default = c.dflt_value;
    columns[c.name] = col;
  }

  const foreignKeys = {};
  for (const fk of all(`PRAGMA foreign_key_list(${name})`)) {
    const fkName = `${name}_${fk.from}_${fk.table}_${fk.to}_fk`;
    foreignKeys[fkName] = {
      name: fkName,
      tableFrom: name,
      tableTo: fk.table,
      columnsFrom: [fk.from],
      columnsTo: [fk.to ?? "id"],
      onDelete: (fk.on_delete || "NO ACTION").toLowerCase().replace(" ", " "),
      onUpdate: (fk.on_update || "NO ACTION").toLowerCase(),
    };
  }

  const indexes = {};
  for (const ix of all(
    "SELECT name, sql FROM sqlite_master WHERE type='index' AND tbl_name=? AND sql IS NOT NULL",
    name,
  )) {
    if (!isSnapshotRepresentable(ix.sql)) continue;
    const unique = /CREATE UNIQUE INDEX/i.test(ix.sql);
    const cols = (ix.sql.match(/\(([^)]*)\)/)?.[1] ?? "")
      .split(",").map((s) => s.trim().replace(/^["'`]|["'`]$/g, "")).filter(Boolean);
    const where = ix.sql.match(/WHERE\s+([\s\S]+)$/i)?.[1]?.trim();
    const entry = { name: ix.name, columns: cols, isUnique: unique };
    if (where) entry.where = where;
    indexes[ix.name] = entry;
  }

  return {
    name,
    columns,
    indexes,
    foreignKeys,
    compositePrimaryKeys: {},
    uniqueConstraints: {},
    checkConstraints: {},
  };
}

const newTables = ["drawing_quantity_expected_scope", "drawing_quantity_expected_scope_events"];
for (const t of newTables) {
  if (!all("SELECT name FROM sqlite_master WHERE type='table' AND name=?", t).length) {
    throw new Error(`table ${t} is not present in the live database; apply 0021 first`);
  }
}

// Predecessor tables are copied verbatim; only the new tables are added.
const tables = { ...prev.tables };
for (const t of newTables) tables[t] = buildTable(t);

const snap = {
  version: prev.version,
  dialect: prev.dialect,
  id: randomUUID(),
  prevId: prev.id,
  tables,
  views: prev.views,
  enums: prev.enums,
  _meta: prev._meta,
  internal: prev.internal,
};

writeFileSync(target, `${JSON.stringify(snap, null, 2)}\n`);
console.log(`wrote ${target}`);
console.log(`  id=${snap.id} prevId=${snap.prevId}`);
console.log(`  tables ${Object.keys(prev.tables).length} -> ${Object.keys(tables).length}`);
for (const t of newTables) {
  console.log(`  ${t}: ${Object.keys(tables[t].columns).length} cols, `
    + `${Object.keys(tables[t].indexes).length} snapshot-representable indexes, `
    + `${Object.keys(tables[t].foreignKeys).length} FKs`);
}
db.close();